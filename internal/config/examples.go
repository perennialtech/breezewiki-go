package config

import (
	"fmt"
	"strings"
)

// Example returns every supported setting with its default.
func Example(format string) (string, error) {
	if format != "ini" && format != "env" {
		return "", fmt.Errorf("unknown config example format %q (want ini or env)", format)
	}
	var b strings.Builder
	b.WriteString("# Generated by make generate-config-examples; do not edit.\n")
	if format == "env" {
		b.WriteString("# For docker run --env-file; nested settings use :: in their names.\n")
		for _, opt := range options {
			fmt.Fprintf(&b, "# %s\nBW_%s=%s\n", opt.description, strings.ToUpper(opt.key), opt.value)
		}
		return b.String(), nil
	}
	section := ""
	// Root keys must precede sections, regardless of their order in options.
	for _, nested := range []bool{false, true} {
		for _, opt := range options {
			group, name, hasSection := strings.Cut(opt.key, "::")
			if hasSection != nested {
				continue
			}
			if hasSection {
				if group != section {
					fmt.Fprintf(&b, "\n[%s]\n", group)
					section = group
				}
			} else {
				name = opt.key
			}
			value := opt.value
			if value != "" {
				value = " " + value
			}
			fmt.Fprintf(&b, "# %s\n%s =%s\n", opt.description, name, value)
		}
	}
	return b.String(), nil
}
